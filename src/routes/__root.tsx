// Estrutura HTML compartilhada: metadados, tema inicial, estilos e scripts do roteador.
function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html:
              "try{if(localStorage.getItem('isp.theme')==='dark')document.documentElement.classList.add('dark')}catch{}",
          }}
        />
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

// Provedores globais disponibilizam cache, autenticação, tema e proteção de acesso às rotas.
function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <ThemeProvider>
          <AccessGate>
            <Outlet />
          </AccessGate>
          <Toaster position="top-right" richColors closeButton />
        </ThemeProvider>
      </AuthProvider>
    </QueryClientProvider>
  );
}
